clc;
clear all;
close all;
t= -10:0.01:10;
A= 3;
x_t1= A.^t;
figure();
subplot(1,3,1);
plot(t,x_t1);
title('Exponential Signal');
xlabel('Time');
ylabel('Amplitude');
grid on;
w= -2*pi:0.01:2*pi;
x_k1= zeros(size(w));
for k=1:length(w)
    x_k1(k)= trapz(t,x_t1.*exp(-j*w(k)*t));
end;
x_kmag1= abs(x_k1);
x_kangle1= angle(x_k1);
subplot(1,3,2);
plot(w,x_kmag1);
title('Magnitude');
xlabel('Time');
ylabel('Amplitude');
subplot(1,3,3);
plot(w,x_kangle1);
title('Phase');
xlabel('Time');
ylabel('Amplitude');
